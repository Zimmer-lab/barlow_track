"""Stage round_pooled_tuning6: one network trained on all 6 tuning recordings at once (pooled training).

The frozen trial 59 recipe (round_sens_src/base_train_config.yaml) with `project_paths` instead of one
project_path: each recording keeps its own path and ViSNet z_scale (read from its round_sens_oat_<label>
train_config.yaml), and the whole network uses crop depth 8 (Flavell included: one network has one crop
shape). Keypoint scaling is unchanged. A direct grid sweeps num_frames PER RECORDING {16, 64, 128, 371}
(96 to 2226 volumes in all) x 3 seeds (the recipe seed and the two loss_volume control replicate seeds):
12 trainings under objective: loss, scored afterwards on all 12 benchmark recordings with
scratch/transfer/score_pooled_round.py.

    python barlow_track/scripts/scratch/round_pooled_src/stage_pooled.py [--dry]

Launch (from the cluster checkout, after git pull):

    D=$B/round_pooled_tuning6
    sbatch --job-name=pooled_tuning6 --output=$D/dispatcher_%j.log barlow_track/scripts/sbatch_dispatcher.sbatch \
        -p $D/hyperparameter_search_template.yaml --direct_parameter_sweep --num_parallel_jobs 4
    # resume after the dispatcher's 7-day limit: the same plus --skip_completed_grid_jobs

Score (after the trainings):

    BARLOW_DISPATCHER=barlow_track/scripts/scratch/transfer/score_pooled_round.py sbatch \
        --output=$D/score_%j.log barlow_track/scripts/sbatch_dispatcher.sbatch --round_dir $D --slurm 8
    python barlow_track/scripts/scratch/transfer/score_pooled_round.py --round_dir $D --report
"""
import argparse
import os

import yaml

B = '/lisc/data/scratch/neurobiology/zimmer/fieseler/barlow_track_revisions/config_files'
NAME = 'round_pooled_tuning6'
LABELS = ['zimmer_1210', 'zimmer_1123', 'flavell_2022033002', 'flavell_2022032402', 'samuel_137', 'samuel_184']
NUM_FRAMES = [16, 64, 128, 371]
SEEDS = [769243397, 763277047, 3712540559]  # recipe seed, replicate_seed(.., 1), replicate_seed(.., 2)
# A 371-per-recording epoch is about the sum of six single-recording epochs (~24 h for 30 epochs on a fast
# node, several times that on a slow one), and training does not resume after a walltime kill. 120 h has
# run before (round_fused_fix_zimmer, --time=7500).
TRAIN_HOURS = 120
BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'round_sens_src', 'base_train_config.yaml')


def recordings(rounds_dir):
    out = []
    for label in LABELS:
        cfg = yaml.safe_load(open(os.path.join(rounds_dir, f'round_sens_oat_{label}', 'train_config.yaml')))
        out.append(dict(label=label, project_path=cfg['project_path'], visnet_z_scale=float(cfg['visnet_z_scale'])))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--rounds_dir', default=B)
    ap.add_argument('--dry', action='store_true', help='print the files instead of writing them')
    a = ap.parse_args()
    d = os.path.join(a.rounds_dir, NAME)
    base = yaml.safe_load(open(BASE))
    cfg = dict(base, project_path=None, visnet_z_scale=None, target_sz_z=8, wandb_name=f'barlow_track_{NAME}',
               project_paths=recordings(a.rounds_dir))
    template = dict(train_hours=TRAIN_HOURS, objective='loss', baseline_params_path=None,
                    hyperparameters=[dict(name='num_frames', type='choice', values=NUM_FRAMES),
                                     dict(name='seed', type='choice', values=SEEDS)])
    files = {'train_config.yaml': (f"# {NAME}: pooled training on the 6 tuning recordings, generated by "
                                   f"round_pooled_src/stage_pooled.py from round_sens_src/base_train_config.yaml\n", cfg),
             'hyperparameter_search_template.yaml': (f"# {NAME}: num_frames PER RECORDING x seed, objective loss "
                                                     f"(scored afterwards with score_pooled_round.py)\n", template)}
    if not a.dry:
        if os.path.exists(os.path.join(d, 'train_config.yaml')):
            raise SystemExit(f"{d} is already staged; remove it first to restage")
        os.makedirs(d)
    for fname, (header, content) in files.items():
        text = header + yaml.safe_dump(content, sort_keys=True, default_flow_style=False)
        if a.dry:
            print(f"--- {os.path.join(d, fname)}\n{text}")
        else:
            with open(os.path.join(d, fname), 'w') as f:
                f.write(text)
            print(f"wrote {os.path.join(d, fname)}")


if __name__ == '__main__':
    main()
